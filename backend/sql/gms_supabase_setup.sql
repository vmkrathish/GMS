-- 100-notifications-per-user retention, enforced in the database —
-- deletes only the SAME user's oldest rows beyond their newest 100.
CREATE OR REPLACE FUNCTION enforce_notification_retention()
RETURNS TRIGGER AS $$
BEGIN
  DELETE FROM notifications
  WHERE user_id = NEW.user_id
    AND id IN (
      SELECT id FROM notifications
      WHERE user_id = NEW.user_id
      ORDER BY created_at DESC, id DESC
      OFFSET 100
    );
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_notification_retention
  AFTER INSERT ON notifications
  FOR EACH ROW
  EXECUTE FUNCTION enforce_notification_retention();

