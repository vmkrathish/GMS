-- ─── 4. BOOKINGS ────────────────────────────────────
CREATE TABLE bookings (
  id              SERIAL         PRIMARY KEY,
  customer_id     INTEGER        NOT NULL,
  provider_id     INTEGER        NOT NULL,
  service_id      INTEGER        NOT NULL,
  -- Two-step verification workflow:
  --   pending → (provider accepts + sets advance) awaiting_advance
  --           → (customer pays) confirmed → in_progress (Visiting) → completed
  --   Reschedule negotiation: reschedule_by_provider ⇄ reschedule_by_customer
  --   (unlimited iterations) until agreement, cancellation or rejection.
  --   Terminal: rejected, cancelled_by_customer, cancelled_by_provider, expired.
  status          VARCHAR(30)    NOT NULL DEFAULT 'pending'
                    CHECK (status IN ('pending','awaiting_advance','confirmed','in_progress',
                       'completed','reschedule_by_provider','reschedule_by_customer',
                       'rejected','cancelled_by_customer','cancelled_by_provider',
                       'expired')),
  scheduled_at    TIMESTAMP      DEFAULT NULL,   -- agreed time
  proposed_time   TIMESTAMP      DEFAULT NULL,   -- current reschedule proposal
  advance_amount  DECIMAL(10,2)  DEFAULT NULL,   -- provider-requested advance
  advance_paid    BOOLEAN        NOT NULL DEFAULT FALSE,
  payment_deadline TIMESTAMP     DEFAULT NULL,   -- optional; passing it → expired
  address         TEXT           DEFAULT NULL,
  customer_lat    DECIMAL(10,7)  DEFAULT NULL,   -- pinned/current location at booking time
  customer_lng    DECIMAL(10,7)  DEFAULT NULL,
  notes           TEXT           DEFAULT NULL,
  cancel_reason   TEXT           DEFAULT NULL,   -- rejection/cancellation reason
  created_at      TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at      TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_booking_customer FOREIGN KEY (customer_id) REFERENCES users(id)    ON DELETE CASCADE,
  CONSTRAINT fk_booking_provider FOREIGN KEY (provider_id) REFERENCES users(id)    ON DELETE CASCADE,
  CONSTRAINT fk_booking_service  FOREIGN KEY (service_id)  REFERENCES services(id) ON DELETE RESTRICT
);
CREATE INDEX idx_bookings_customer ON bookings (customer_id);
CREATE INDEX idx_bookings_provider ON bookings (provider_id);
CREATE INDEX idx_bookings_status   ON bookings (status);
CREATE TRIGGER trg_bookings_updated_at
  BEFORE UPDATE ON bookings
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

