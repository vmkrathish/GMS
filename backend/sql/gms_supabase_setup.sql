BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ─── Helper: replaces MySQL's ST_Distance_Sphere(POINT(lng,lat), POINT(lng,lat))
--      geospatial function used for GMS's "nearby providers" distance search.
--      Great-circle (haversine) distance in meters between two lng/lat points,
--      using the same default earth radius (6,370,986 m) MySQL uses.
--      Call as: gms_distance_sphere(lon1, lat1, lon2, lat2)
CREATE FUNCTION gms_distance_sphere(
  lon1 DOUBLE PRECISION, lat1 DOUBLE PRECISION,
  lon2 DOUBLE PRECISION, lat2 DOUBLE PRECISION
) RETURNS DOUBLE PRECISION AS $$
DECLARE
  r        DOUBLE PRECISION := 6370986;
  rad_lat1 DOUBLE PRECISION := radians(lat1);
  rad_lat2 DOUBLE PRECISION := radians(lat2);
  dlat     DOUBLE PRECISION := radians(lat2 - lat1);
  dlon     DOUBLE PRECISION := radians(lon2 - lon1);
  a        DOUBLE PRECISION;
  c        DOUBLE PRECISION;
BEGIN
  IF lon1 IS NULL OR lat1 IS NULL OR lon2 IS NULL OR lat2 IS NULL THEN
    RETURN NULL;
  END IF;
  a := sin(dlat / 2) * sin(dlat / 2)
     + cos(rad_lat1) * cos(rad_lat2) * sin(dlon / 2) * sin(dlon / 2);
  c := 2 * atan2(sqrt(a), sqrt(1 - a));
  RETURN r * c;
END;
$$ LANGUAGE plpgsql IMMUTABLE;

