CREATE TABLE users (
  id           SERIAL          PRIMARY KEY,
  phone        VARCHAR(15)     NOT NULL UNIQUE,
  email        VARCHAR(190)    DEFAULT NULL UNIQUE,
  name         VARCHAR(100)    NOT NULL DEFAULT '',
  password_hash VARCHAR(255)   DEFAULT NULL,
  avatar_url   VARCHAR(500)    DEFAULT NULL,
  bio          TEXT            DEFAULT NULL,
  role         VARCHAR(10)     NOT NULL DEFAULT 'customer'
                 CHECK (role IN ('customer','provider')),
  -- You-page profile model ↓
  dial_code            VARCHAR(6)    NOT NULL DEFAULT '+91',
  location_text        VARCHAR(200)  NOT NULL DEFAULT '',   -- live-location display text
  address_line1        VARCHAR(200)  NOT NULL DEFAULT '',
  area_street_village  VARCHAR(200)  NOT NULL DEFAULT '',
  landmark             VARCHAR(200)  NOT NULL DEFAULT '',
  city                 VARCHAR(100)  NOT NULL DEFAULT '',
  district             VARCHAR(100)  NOT NULL DEFAULT '',
  state                VARCHAR(100)  NOT NULL DEFAULT '',
  pincode              VARCHAR(12)   NOT NULL DEFAULT '',
  country              VARCHAR(100)  NOT NULL DEFAULT 'India',
  latitude             DECIMAL(10,7) DEFAULT NULL,          -- provider/customer place
  longitude            DECIMAL(10,7) DEFAULT NULL,
  fcm_token    TEXT            DEFAULT NULL,
  last_seen_at TIMESTAMP       DEFAULT NULL,
  is_active    BOOLEAN         NOT NULL DEFAULT TRUE,
  created_at   TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at   TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
  -- Safeguard against garbage values (typos, bare local file paths,
  -- a missing WHERE clause on a manual UPDATE). Allows either a full
  -- external URL (http/https — e.g. a Cloudinary or pravatar.cc link)
  -- OR a relative server path starting with /static/ (our own
  -- uploads — stored relative so they stay valid no matter what
  -- host/port the backend runs on later, see fix_avatar_url_portability.sql).
